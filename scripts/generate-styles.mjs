import {styleCategories, resolveStyles} from './style-source.mjs';
const banner = '// Generated by scripts/generate.mjs; edit tokens/styles.json, not this file.\n';
const json = value => JSON.stringify(value, null, 2);
const capitalized = value => value[0].toUpperCase() + value.slice(1);
const models = {
  typography: {name: 'TypographyToken', properties: {size:'Double', weight:'Double', lineHeight:'Double', tracking:'Double', relativeTo:'String', monospacedDigits:'Bool'}},
  curve: {name: 'CubicBezierToken', properties: {x1:'Double', y1:'Double', x2:'Double', y2:'Double'}},
  spring: {name: 'SpringToken', properties: {response:'Double', dampingFraction:'Double', blendDuration:'Double'}},
  shadow: {name: 'ShadowToken', properties: {colorToken:'String', opacity:'Double', radius:'Double', x:'Double', y:'Double'}}
};

export function renderStyles(source, colorSource) {
  const data = resolveStyles(source, colorSource);
  const ids = category => Object.keys(data.tokens).filter(id => id.startsWith(category + '.'));
  const returnType = category => models[category]?.name ?? 'Double';
  const tsType = category => models[category]?.name ?? 'number';
  const js = banner + `const data = ${json(data)};
function freeze(value) {
  if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); }
  return value;
}
freeze(data);
export const styleSchemaVersion = data.schemaVersion;
export const styleUnits = data.units;
export const styleTokenIDs = Object.freeze(Object.keys(data.tokens));
function lookup(category, id) {
  if (typeof id !== 'string' || !id.startsWith(category + '.') || !Object.hasOwn(data.tokens, id)) throw new Error('unknown style token: ' + String(id));
  return data.tokens[id];
}
` + styleCategories.map(category => `export const ${category}IDs = Object.freeze(styleTokenIDs.filter(id => id.startsWith('${category}.')));
export function ${category}(id) { return lookup('${category}', id); }
`).join('');
  const dts = banner + `import type {TokenID} from './index.js';
export declare const styleSchemaVersion: '1.0.0';
export declare const styleUnits: Readonly<{length: 'logical-unit'; duration: 'second'; weight: 'css-weight'}>;
` + Object.values(models).map(model => `export interface ${model.name} { ${Object.entries(model.properties).map(([name,type]) => `readonly ${name}: ${type === 'Double' ? 'number' : type === 'Bool' ? 'boolean' : name === 'colorToken' ? 'TokenID' : 'string'}`).join('; ')} }\n`).join('') + styleCategories.map(category => `export type ${capitalized(category)}ID = ${ids(category).map(JSON.stringify).join(' | ')};
export declare const ${category}IDs: readonly ${capitalized(category)}ID[];
export declare function ${category}(id: ${capitalized(category)}ID): ${tsType(category)};
`).join('') + `export type StyleTokenID = ${styleCategories.map(category => capitalized(category)+'ID').join(' | ')};
export declare const styleTokenIDs: readonly StyleTokenID[];
`;
  const swiftValue = (category, value) => {
    const model = models[category];
    if (!model) return String(value);
    return `${model.name}(${Object.entries(model.properties).map(([name,type]) => `${name}: ${type === 'String' ? JSON.stringify(value[name]) : String(value[name])}`).join(', ')})`;
  };
  const swift = banner + `extension StyleTokens {
` + styleCategories.map(category => `    static let ${category}Table: [String: ${returnType(category)}] = [
${ids(category).map(id => `        "${id}": ${swiftValue(category,data.tokens[id])}`).join(',\n')}
    ]
`).join('') + '}\n';
  return {'dist/styles.js':js,'dist/styles.d.ts':dts,'dist/styles.resolved.json':json(data)+'\n','Sources/DesignTokens/GeneratedStyles.swift':swift};
}
